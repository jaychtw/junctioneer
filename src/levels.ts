import type { Level, Rail, Port } from "./engine";
const rail = (
  id: string,
  x: number,
  z: number,
  ports: Port[],
  extra: Partial<Rail> = {},
): Rail => ({ id, x, z, ports, kind: "rail", ...extra });
const terminal = (
  id: string,
  x: number,
  z: number,
  port: Port,
  end?: "start" | "dead",
): Rail => rail(id, x, z, [port], { kind: "terminus", end });
const junction = (
  id: string,
  x: number,
  z: number,
  stem: Port,
  branches: [Port, Port],
  initial: 0 | 1,
): Rail =>
  rail(id, x, z, [stem, ...branches], {
    kind: "junction",
    stem,
    branches,
    initial,
  });
